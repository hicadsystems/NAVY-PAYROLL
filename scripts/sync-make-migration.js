// Writes config/sql/migrations/<ts>_sync_control_tables.sql from services/sync/schema.js.
// The migrator runs every file on all six databases; each statement here only
// acts when the current database is the master (MASTER_DB, default hicaddata).
//
//   node scripts/sync-make-migration.js [timestamp] [masterDb]

const fs = require("fs");
const path = require("path");
const { TABLES } = require("../services/sync/schema");

const ts = process.argv[2] || "20261022_090000";
const master = process.argv[3] || process.env.MYSQL_DB_OFFICERS || "hicaddata";
const file = path.join(__dirname, "..", "config", "sql", "migrations", `${ts}_sync_control_tables.sql`);

// One line, no single quotes (the DDL goes inside a quoted string).
const oneLine = (s) => s.replace(/\s+/g, " ").trim().replace(/'/g, '"');

let up = "";
let down = "";
for (const [name, body] of Object.entries(TABLES)) {
  const ddl = oneLine(`CREATE TABLE IF NOT EXISTS ${name} (${body}) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4`);
  up += `-- ${name}
SET @sql = IF(DATABASE() = '${master}',
  '${ddl}',
  'SELECT "not the master database, skipping ${name}"');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

`;
  down =
    `SET @sql = IF(DATABASE() = '${master}', 'DROP TABLE IF EXISTS ${name}', 'SELECT 1');
PREPARE stmt FROM @sql;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

` + down;
}

const out = `-- Migration: sync_control_tables
-- Created: ${new Date().toISOString()}
-- Payslip Sync control tables (website contract, "Control tables").
-- Generated by scripts/sync-make-migration.js from services/sync/schema.js — edit there.
-- Only the master database (${master}) gets these tables.

-- =========================
-- UP
-- =========================

${up}
-- =========================
-- DOWN
-- =========================

${down}`;

fs.writeFileSync(file, out);
console.log("wrote", file);
